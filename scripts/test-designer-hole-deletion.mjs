import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = fileURLToPath(new URL('../', import.meta.url));
const privateNames = ['removeItemsWithOwnedEndTapping', 'createProfileObject', 'createItem'];
const result = await build({
  absWorkingDir: root,
  stdin: { contents: `export { ${privateNames.join(', ')}, synchronizeDesignerSceneItems, normalizeDesignItems, buildProductionData } from './components/DIYDesigner.tsx';`, resolveDir: root },
  bundle: true, platform: 'node', format: 'cjs', write: false,
  define: { 'import.meta.env.BASE_URL': '"/"' },
  plugins: [{ name: 'expose-deletion-boundary', setup(builder) {
    builder.onLoad({ filter: /components\/DIYDesigner\.tsx$/ }, async ({ path }) => ({
      contents: `${await readFile(path, 'utf8')}\nexport { ${privateNames.join(', ')} };`, loader: 'tsx',
      resolveDir: fileURLToPath(new URL('../components/', import.meta.url)),
    }));
  } }],
});
const module = { exports: {} };
new Function('require', 'module', 'exports', result.outputFiles[0].text)(createRequire(import.meta.url), module, module.exports);
const api = module.exports;
const hole = { id: 'same-local-hole-id', type: 'countersunk', side: 'A', positionMm: 200 };
const profile = { ...api.createItem('profile'), id: 'profile-a', variantId: '3030', length: 600,
  tappingLeft: true, holes: [hole] };
const neighbour = { ...profile, id: 'profile-b', position: [0, 0, 300], holes: [{ ...hole }] };
const screw = { ...api.createItem('screw'), id: 'screw-a', linkedProfileId: profile.id,
  linkedHoleId: hole.id, screwHead: 'socket_cylinder', autoGenerated: true };
const otherScrew = { ...screw, id: 'screw-b', linkedProfileId: neighbour.id };
const loose = { ...api.createItem('screw'), id: 'loose' };
const source = [profile, neighbour, screw, otherScrew, loose];
const original = JSON.stringify(source);
const remove = (items, ids) => api.synchronizeDesignerSceneItems(api.removeItemsWithOwnedEndTapping(items, new Set(ids), true));
const removed = remove(source, ['screw-a']);
assert.deepEqual(removed.find(x => x.id === profile.id).holes, []);
assert.deepEqual(removed.find(x => x.id === neighbour.id).holes, [hole], 'same hole ID on another profile is independent');
assert.ok(removed.some(x => x.id === otherScrew.id));
assert.ok(!removed.some(x => x.id === screw.id));
assert.equal(removed.find(x => x.id === profile.id).tappingLeft, true, 'independent end tapping is retained');
assert.equal(JSON.stringify(source), original, 'undo snapshot is immutable');
const restored = api.synchronizeDesignerSceneItems(api.normalizeDesignItems(JSON.parse(JSON.stringify(removed))));
assert.equal(restored.find(x => x.id === profile.id).holes.length, 0, 'save/reopen must not regenerate a deleted hole');
assert.ok(!api.buildProductionData(restored, 'cn').holes.some(x => x.partId === profile.id));
const decorations = item => {
  const mesh = api.createProfileObject(item, false);
  let count = 0;
  mesh.traverse(child => { if (child.userData.holeDecoration) count++; });
  return count;
};
assert.ok(decorations(profile) > 0, 'reproduce the amber marker when a hole survives without its screw');
assert.equal(decorations(restored.find(x => x.id === profile.id)), 0, 'deleted machining must produce no opening/rim decoration');
assert.equal(remove(source, ['loose']).find(x => x.id === profile.id).holes.length, 1);
assert.ok(remove(source, ['screw-a', 'screw-b']).filter(x => x.kind === 'profile').every(x => x.holes.length === 0));
const duplicateLink = { ...screw, id: 'duplicate-link', autoGenerated: false };
assert.ok(!remove([...source, duplicateLink], ['screw-a']).some(x => x.id === duplicateLink.id));
// The hole-list delete path removes its generated screw on the same commit.
const withoutHole = api.synchronizeDesignerSceneItems(source.map(x => x.id === profile.id ? { ...x, holes: [] } : x));
assert.ok(!withoutHole.some(x => x.id === screw.id));
// Stool synchronization must honor the same deletion instead of restoring its joint.
const stoolProfile = { ...profile, id: 'parametric-stool-test-profile' };
const stoolScrew = { ...screw, linkedProfileId: stoolProfile.id };
assert.equal(remove([stoolProfile, stoolScrew], [screw.id]).find(x => x.id === stoolProfile.id).holes.length, 0);
console.log('PASS: linked-hole deletion, amber rim removal, machining export/save/reopen, batch/profile isolation, loose screws, duplicate links, direct hole deletion and stool synchronization.');

const keepHoles = api.synchronizeDesignerSceneItems(api.removeItemsWithOwnedEndTapping(source, new Set(['screw-a']), false));
assert.equal(keepHoles.find(x => x.id === profile.id).holes.length, 1, 'keep-hole choice retains machining');
assert.ok(!keepHoles.some(x => x.id === screw.id));
assert.ok(decorations(keepHoles.find(x => x.id === profile.id)) > 0, 'keep-hole choice intentionally shows the marker');
console.log('PASS: explicit keep-hole choice retains machining and its amber marker.');
