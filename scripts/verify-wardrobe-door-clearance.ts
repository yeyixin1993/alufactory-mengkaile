import assert from 'node:assert/strict';
import { buildWardrobeTemplate } from '../utils/parametricFurniture';
import { completeParametricFurnitureTemplate, detectCabinetDoorOpenings, fitCabinetDoorToOpening, synchronizeDesignerSceneItems, validateDisplayRackConnectionSystem } from '../components/DIYDesigner';

for (const frame of ['2040_2020', '2047_2020', '3030'] as const) {
  for (const edge of ['open', 'sealed'] as const) {
    const initial = completeParametricFurnitureTemplate(buildWardrobeTemplate(1300,600,1200,2,2,frame,'none',edge));
    assert(initial.check.valid, initial.check.issues.join(';'));
    const baseline = initial.items;
    const fronts = baseline.filter(item => item.wardrobeDoorClearance?.frontRail);
    assert.equal(fronts.length,4);
    assert(fronts.every(item => !item.wardrobeFrontSetbackMm));
    const opening = detectCabinetDoorOpenings(baseline).sort((a,b) => a.outer.left-b.outer.left)[0];
    assert(opening);
    const door: any = fitCabinetDoorToOpening({ id: 'door-test', name: 'Test door', kind: 'cabinet_door', colorId: 'natural', quantity: 1, position:[0,0,0], rotation:[0,0,0], doorMaterial: 'marine', doorOverlay:'inset', thickness:18 },opening);
    const moved = synchronizeDesignerSceneItems([...baseline,door]);
    const active = moved.filter(item => item.wardrobeDoorClearance?.frontRail && item.wardrobeDoorClearance.applied);
    assert.equal(active.length,2, `${frame}/${edge}: only the door's column should recess`);
    const offset = frame === '3030' ? 30 : frame === '2047_2020' ? 27 : 20;
    active.forEach(rail => {
      assert.equal(rail.wardrobeFrontSetbackMm, offset);
      assert.equal(rail.position[2], baseline.find(item => item.id===rail.id)!.position[2]-offset);
    });
    const projection = (items: typeof baseline) => items.filter(item => item.wardrobeDoorClearance).map(item => ({ id:item.id,position:item.position,height:item.height,active:item.wardrobeDoorClearance!.applied }));
    assert.deepEqual(projection(synchronizeDesignerSceneItems(moved)),projection(moved),'Repeated synchronization must not drift');
    for (const mode of ['full','half','deleted']) {
      const changed = moved.flatMap(item => item.id !== door.id ? [item] : mode==='deleted' ? [] : [{...item,doorOverlay:mode as 'full'|'half'}]);
      const restored = synchronizeDesignerSceneItems(changed);
      assert.deepEqual(projection(restored),projection(baseline), `${frame}/${edge}/${mode}: restore original dimensions`);
      assert(restored.filter(item=>item.kind==='connector' && item.autoGenerated).every(item=>item.lockedPosition), 'Restored brackets seated');
    }
    assert(moved.filter(item=>['connector','hidden_connector'].includes(item.kind) && item.autoGenerated).every(item=>item.lockedPosition),`${frame}: inset brackets seated`);
    if(frame==='3030') {
      const check = validateDisplayRackConnectionSystem(moved);
      assert(check.valid,check.issues.join(';'));
      active.forEach(rail => assert.equal(moved.filter(item => item.kind==='hidden_connector' && item.attachedProfileIds?.includes(rail.id)).length,2));
    }
    console.log(`${frame}/${edge}: flush by default; inset-only column clearance; full/half/delete restore; stable sync passed`);
  }
}
