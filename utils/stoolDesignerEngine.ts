const normalizeQuarterTurnDegrees = (degrees: number) => {
  let normalized = (Math.round(degrees / 90) * 90) % 360;
  if (normalized <= -180) normalized += 360;
  if (normalized > 180) normalized -= 360;
  return Object.is(normalized, -0) ? 0 : normalized;
};


const rayProfileInterval = (
  originWorldMm: THREE.Vector3,
  directionWorld: THREE.Vector3,
  target: DIYSceneItem,
) => {
  if (target.kind !== 'profile') return null;
  const inverseQuaternion = itemQuaternion(target).invert();
  const origin = originWorldMm.clone()
    .sub(new THREE.Vector3(...target.position))
    .applyQuaternion(inverseQuaternion);
  const direction = directionWorld.clone().applyQuaternion(inverseQuaternion).normalize();
  const [widthMm, heightMm] = profileSize(target.variantId);
  const halfSizes = [
    Math.max(20, target.length || 1000) / 2,
    heightMm / 2,
    widthMm / 2,
  ];
  const originValues = [origin.x, origin.y, origin.z];
  const directionValues = [direction.x, direction.y, direction.z];
  let entry = -Infinity;
  let exit = Infinity;
  for (let axisIndex = 0; axisIndex < 3; axisIndex += 1) {
    const axisOrigin = originValues[axisIndex];
    const axisDirection = directionValues[axisIndex];
    const halfSize = halfSizes[axisIndex];
    if (Math.abs(axisDirection) < 1e-7) {
      if (axisOrigin < -halfSize || axisOrigin > halfSize) return null;
      continue;
    }
    const first = (-halfSize - axisOrigin) / axisDirection;
    const second = (halfSize - axisOrigin) / axisDirection;
    entry = Math.max(entry, Math.min(first, second));
    exit = Math.min(exit, Math.max(first, second));
    if (entry > exit) return null;
  }
  if (exit < 0) return null;
  return { entry: Math.max(0, entry), exit };
};


const linkedScrewTransform = (profile: DIYSceneItem, hole: DrillHole, items: DIYSceneItem[]) => {
  const [widthMm, heightMm] = profileSize(profile.variantId);
  const lengthMm = Math.max(20, profile.length || 1000);
  const grooveCount = Math.max(1, getProfileGrooveCount(profile.variantId, hole.side));
  const physicalGrooveIndex = THREE.MathUtils.clamp(
    getHolePhysicalGrooveIndex(hole, profile.variantId),
    0,
    grooveCount - 1,
  );
  const grooveSpanMm = hole.side === 'A' || hole.side === 'C' ? widthMm : heightMm;
  const grooveCoordinateMm = grooveSpanMm / 2
    - ((physicalGrooveIndex + 0.5) * grooveSpanMm) / grooveCount;
  const penetrationMm = hole.side === 'A' || hole.side === 'C' ? heightMm : widthMm;
  // Countersunk heads sit inside the profile face. A button head moves to an
  // inner slot only when the hole explicitly records that seat; a generic
  // through-hole must stay on its marked surface instead of being guessed.
  // The physical counterbore leaves the socket head visible at the groove
  // surface. The rendered cylinder head is 4.5mm tall, so a 4mm recess keeps
  // only its top lip/socket exposed in opaque mode while the shaft remains
  // inside the extrusion.
  const internalButtonHead = hole.type === 'through'
    && screwHeadForHole(hole) === 'button_socket'
    && hole.fastenerSeat === 'internal_slot';
  const headEmbedMm = hole.type === 'countersunk'
    ? 4
    : internalButtonHead
      ? Math.max(0, penetrationMm - 5)
      : 0;
  const localPosition = new THREE.Vector3(
    -lengthMm / 2 + hole.positionMm,
    0,
    0,
  );
  const localOutward = new THREE.Vector3();
  const localRotation = new THREE.Quaternion();
  if (hole.side === 'A') {
    localPosition.y = heightMm / 2;
    localOutward.set(0, 1, 0);
  } else if (hole.side === 'C') {
    localPosition.y = -heightMm / 2;
    localOutward.set(0, -1, 0);
    localRotation.setFromEuler(new THREE.Euler(Math.PI, 0, 0, 'XYZ'));
  } else if (hole.side === 'B') {
    localPosition.y = grooveCoordinateMm;
    localPosition.z = widthMm / 2;
    localOutward.set(0, 0, 1);
    localRotation.setFromEuler(new THREE.Euler(Math.PI / 2, 0, 0, 'XYZ'));
  } else {
    localPosition.y = grooveCoordinateMm;
    localPosition.z = -widthMm / 2;
    localOutward.set(0, 0, -1);
    localRotation.setFromEuler(new THREE.Euler(-Math.PI / 2, 0, 0, 'XYZ'));
  }
  if (hole.side === 'A' || hole.side === 'C') localPosition.z = grooveCoordinateMm;
  const screwOutward = hole.fastenerDirection === 'outward';
  if (screwOutward) {
    localOutward.multiplyScalar(-1);
    localRotation.multiply(new THREE.Quaternion().setFromEuler(new THREE.Euler(Math.PI, 0, 0, 'XYZ')));
  }
  // The screw model's head occupies local +Y. Move its seat into the
  // extrusion by exactly the head depth so the top is flush with the surface.
  localPosition.addScaledVector(localOutward, -headEmbedMm);

  const profileQuaternion = itemQuaternion(profile);
  const worldPosition = localPosition
    .applyQuaternion(profileQuaternion)
    .add(new THREE.Vector3(...profile.position));
  const penetrationDirection = localOutward.clone().multiplyScalar(-1).applyQuaternion(profileQuaternion).normalize();
  const sourceExitDistance = Math.max(1, penetrationMm - headEmbedMm);
  const receivingProfiles = items
    .filter((item) => item.kind === 'profile' && item.id !== profile.id)
    .map((target) => {
      const interval = rayProfileInterval(worldPosition, penetrationDirection, target);
      return interval ? { target, ...interval } : null;
    })
    .filter((entry): entry is { target: DIYSceneItem; entry: number; exit: number } => Boolean(entry))
    // A valid mating extrusion starts at, or shortly after, the source exit.
    // This avoids visually extending a screw toward an unrelated remote part.
    .filter((entry) => entry.entry >= sourceExitDistance - 2 && entry.entry <= sourceExitDistance + 35)
    .sort((first, second) => first.entry - second.entry);
  const receiver = receivingProfiles[0];
  const receiverInsertionMm = receiver
    ? THREE.MathUtils.clamp((receiver.exit - receiver.entry) * 0.55, 6, 12)
    : 8;
  const screwLengthMm = Math.max(
    12,
    Math.ceil((receiver ? receiver.entry : sourceExitDistance) + receiverInsertionMm),
  );
  const worldQuaternion = profileQuaternion.clone().multiply(localRotation);
  const worldEuler = new THREE.Euler().setFromQuaternion(worldQuaternion, 'XYZ');
  return {
    position: [
      Number(worldPosition.x.toFixed(3)),
      Number(worldPosition.y.toFixed(3)),
      Number(worldPosition.z.toFixed(3)),
    ] as Vec3,
    rotation: [
      Math.round(THREE.MathUtils.radToDeg(worldEuler.x)),
      Math.round(THREE.MathUtils.radToDeg(worldEuler.y)),
      Math.round(THREE.MathUtils.radToDeg(worldEuler.z)),
    ] as Vec3,
    lengthMm: hole.fastenerLengthMm || screwLengthMm,
  };
};


const createLinkedScrew = (
  profile: DIYSceneItem,
  hole: DrillHole,
  items: DIYSceneItem[],
): DIYSceneItem | null => {
  const screwHead = screwHeadForHole(hole);
  if (!screwHead) return null;
  const transform = linkedScrewTransform(profile, hole, items);
  const accessoryProfileSize = profileAccessorySeriesFromVariant(profile.variantId);
  const orderSpec = getDiyScrewOrderSpec(accessoryProfileSize, screwHead, transform.lengthMm);
  return {
    ...createItem('screw'),
    id: makeId(),
    name: screwHead === 'socket_cylinder'
      ? 'Socket cylinder-head screw'
      : screwHead === 'flat_socket'
        ? 'Flat-head socket screw'
        : 'Button-head socket screw',
    position: transform.position,
    rotation: transform.rotation,
    width: 10,
    height: orderSpec.lengthMm,
    colorId: 'natural',
    accessoryProfileSize,
    screwHead,
    threadSize: orderSpec.threadSize,
    fastenerLengthMm: orderSpec.lengthMm,
    fastenerCatalogId: orderSpec.catalogItemId || undefined,
    linkedProfileId: profile.id,
    linkedHoleId: hole.id,
    fastenerSeat: hole.fastenerSeat,
    attachmentKey: hole.jointKey,
    autoGenerated: true,
    remark: `${profile.variantId || '2020'} · ${hole.side} · ${hole.positionMm}mm${hole.jointKey?.endsWith(':DRILL-TAP') && screwHead === 'button_socket' ? '；内槽头座连接端攻丝；套装附带弹性扣件未用于此节点' : ''}`,
  };
};


const syncLinkedScrews = (source: DIYSceneItem[], profileIds?: ReadonlySet<string>, holeIds?: ReadonlySet<string>) => {
  const profiles = new Map(source.filter((item) => item.kind === 'profile').map((item) => [item.id, item]));
  return source.flatMap((item) => {
    if (item.kind !== 'screw' || !item.autoGenerated || !item.linkedProfileId || !item.linkedHoleId) return [item];
    if (profileIds && !profileIds.has(item.linkedProfileId)) return [item];
    if (holeIds && !holeIds.has(item.linkedHoleId)) return [item];
    const profile = profiles.get(item.linkedProfileId);
    const hole = profile?.holes?.find((entry) => entry.id === item.linkedHoleId);
    if (!profile || !hole || !screwHeadForHole(hole)) return [];
    const transform = linkedScrewTransform(profile, hole, source);
    const accessoryProfileSize = profileAccessorySeriesFromVariant(profile.variantId);
    // APS exports used a shaft-centre/inward pose and sometimes omitted the
    // screw's explicit specification. Convert that pose to our head-seat frame,
    // but do not replace a source M6x35 with the 3030 default M8x45. Explicit
    // screw/linked-hole disagreement must remain visible to the quality checker.
    if (item.id.startsWith('aps-screw-') && hole.id.startsWith('aps-')) {
      const threadSize = item.threadSize || hole.threadSize;
      const lengthMm = item.fastenerLengthMm || item.height || hole.fastenerLengthMm;
      const screwHead = item.screwHead || screwHeadForHole(hole) || undefined;
      const exactSpec = findDesignerFastenerExact({
        profileId: profile.variantId || '', headType: screwHead,
        threadSize, lengthMm,
      });
      return [{
        ...item, position: transform.position, rotation: transform.rotation,
        accessoryProfileSize, screwHead, threadSize,
        height: lengthMm, fastenerLengthMm: lengthMm,
        fastenerCatalogId: exactSpec?.id,
      }];
    }
    const orderSpec = getDiyScrewOrderSpec(accessoryProfileSize, screwHeadForHole(hole) || item.screwHead, transform.lengthMm);
    return [{
      ...item,
      position: transform.position,
      rotation: transform.rotation,
      height: orderSpec.lengthMm,
      accessoryProfileSize,
      screwHead: screwHeadForHole(hole) || item.screwHead,
      threadSize: orderSpec.threadSize,
      fastenerLengthMm: orderSpec.lengthMm,
      fastenerCatalogId: orderSpec.catalogItemId || undefined,
      attachmentKey: hole.jointKey || item.attachmentKey,
      fastenerSeat: hole.fastenerSeat,
      ...(hole.jointKey?.endsWith(':DRILL-TAP') && screwHeadForHole(hole) === 'button_socket'
        ? { remark: `${profile.variantId || '2020'} · ${hole.side} · ${hole.positionMm}mm；内槽头座连接端攻丝；套装附带弹性扣件未用于此节点` } : {}),
    }];
  });
};


const withAutoFilledScrews = (source: DIYSceneItem[], profileIds?: ReadonlySet<string>, holeIds?: ReadonlySet<string>) => {
  const next = [...source];
  const linkedKeys = new Set(next
    .filter((item) => item.kind === 'screw' && item.linkedProfileId && item.linkedHoleId)
    .map((item) => `${item.linkedProfileId}:${item.linkedHoleId}`));
  source.filter((item) => item.kind === 'profile' && (!profileIds || profileIds.has(item.id))).forEach((profile) => {
    (profile.holes || []).forEach((hole) => {
      if (holeIds && !holeIds.has(hole.id)) return;
      const key = `${profile.id}:${hole.id}`;
      if (!screwHeadForHole(hole) || linkedKeys.has(key)) return;
      const screw = createLinkedScrew(profile, hole, next);
      if (!screw) return;
      next.push(screw);
      linkedKeys.add(key);
    });
  });
  return syncLinkedScrews(next, profileIds, holeIds);
};


