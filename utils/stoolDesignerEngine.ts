const validateNo5SceneItem = (
  connector: DIYSceneItem,
  source: DIYSceneItem[],
  nodeByJoint: ReadonlyMap<string, PhysicalConnectionNode> = no5NodeMap(source),
): No5ValidationReport | null => {
  if (connector.kind !== 'hidden_connector') return null;
  const node = nodeByJoint.get(no5JointKeyFor(connector));
  if (!node) return null;
  const itemsWithCurrentConnector = source.some((item) => item.id === connector.id)
    ? source.map((item) => item.id === connector.id ? connector : item)
    : [...source, connector];
  return validateNo5HiddenConnector({
    node,
    connector,
    items: itemsWithCurrentConnector,
  });
};


const no5ReportIsReady = (report: No5ValidationReport | null | undefined) => Boolean(
  report
  && report.status === 'pass'
  && report.manufacturingReady
  && report.installationReady,
);


/** Refresh versioned No.5 evidence after every geometry/accessory mutation. */
const withValidatedNo5Connections = (source: DIYSceneItem[]) => {
  const nodeByJoint = no5NodeMap(source);
  return source.map((item) => {
    if (item.kind !== 'hidden_connector') return item;
    const report = validateNo5SceneItem(item, source, nodeByJoint);
    return {
      ...item,
      no5Validation: report || undefined,
      installationStage: item.installationStage || 'connection',
    };
  });
};


const buildValidatedNo5ConnectorForJoint = (
  source: DIYSceneItem[],
  joint: AutoConnectionJoint,
): { item: DIYSceneItem; report: No5ValidationReport } | null => {
  const targetIds = [joint.first.id, joint.second.id].sort();
  const removedHoleLinks = new Set(source.flatMap((item) => (
    item.kind === 'profile'
      ? (item.holes || [])
        .filter((hole) => hole.jointKey === `${joint.key}:DRILL-TAP`)
        .map((hole) => `${item.id}:${hole.id}`)
      : []
  )));
  const jointBase = source.flatMap((item): DIYSceneItem[] => {
    const attachmentMatches = Boolean(item.attachmentKey && (
      item.attachmentKey === joint.key || item.attachmentKey.startsWith(`${joint.key}:`)
    ));
    const pairMatches = isConnectionAccessoryKind(item.kind)
      && (item.attachedProfileIds || []).length === 2
      && [...(item.attachedProfileIds || [])].sort().every((id, index) => id === targetIds[index]);
    // The profile pair is the physical identity. Legacy and duplicated records
    // can have an outdated face suffix, so remove both identities while
    // solving exactly one verified replacement for this joint.
    if (isConnectionAccessoryKind(item.kind) && (attachmentMatches || pairMatches)) return [];
    if (
      item.kind === 'screw'
      && item.linkedProfileId
      && item.linkedHoleId
      && removedHoleLinks.has(`${item.linkedProfileId}:${item.linkedHoleId}`)
    ) return [];
    if (item.kind !== 'profile') return [item];
    const holes = (item.holes || []).filter((hole) => hole.jointKey !== `${joint.key}:DRILL-TAP`);
    return holes.length === (item.holes || []).length ? [item] : [{ ...item, holes }];
  });
  const probe = createItem('hidden_connector', jointBase.length, joint.series);
  const placements = accessoryPlacementCandidates(probe, jointBase)
    .filter((placement) => (
      placement.joint
      && [...placement.targetProfileIds].sort().every((id, index) => id === targetIds[index])
    ))
    .sort((first, second) => first.key.localeCompare(second.key));
  const nodeByJoint = no5NodeMap(jointBase);
  for (const placement of placements) {
    const item: DIYSceneItem = {
      ...createItem('hidden_connector', jointBase.length, joint.series),
      position: placement.position.toArray().map((value) => Number((value * SCENE_SCALE).toFixed(3))) as Vec3,
      rotation: placement.rotation,
      lockedPosition: true,
      autoGenerated: true,
      attachedProfileIds: placement.targetProfileIds,
      attachmentKey: placement.key,
      installationStage: 'connection',
    };
    const report = validateNo5SceneItem(item, jointBase, nodeByJoint);
    if (report && no5ReportIsReady(report)) return { item: { ...item, no5Validation: report }, report };
  }
  return null;
};


const findAccessoryPlacement = (
  accessory: DIYSceneItem,
  items: DIYSceneItem[],
  referencePosition: THREE.Vector3,
  preferredProfileId?: string | null,
  maxDistance = Infinity,
) => accessoryPlacementCandidates(accessory, items)
  .filter((candidate) => !preferredProfileId || candidate.targetProfileIds.includes(preferredProfileId))
  .map((candidate) => ({
    candidate,
    distance: candidate.position.distanceTo(referencePosition),
    priority: candidate.joint ? -candidate.targetProfileIds.length : 1,
  }))
  .filter((entry) => entry.distance <= maxDistance)
  .sort((first, second) => first.priority - second.priority || first.distance - second.distance)[0]?.candidate || null;


