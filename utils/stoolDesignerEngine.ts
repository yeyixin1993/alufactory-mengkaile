const displayRackBaseVerticalDepthMembers = (
  joint: AutoConnectionJoint,
  firstEnd: -1 | 1 | null,
  secondEnd: -1 | 1 | null,
) => {
  if (
    firstEnd === null
    || secondEnd === null
    || !joint.first.id.startsWith('display-rack-3-')
    || !joint.second.id.startsWith('display-rack-3-')
  ) return null;
  const firstVertical = Math.abs(joint.firstBox.axes[0].y) > 0.9;
  const secondVertical = Math.abs(joint.secondBox.axes[0].y) > 0.9;
  const firstDepth = Math.abs(joint.firstBox.axes[0].z) > 0.9;
  const secondDepth = Math.abs(joint.secondBox.axes[0].z) > 0.9;
  if (!((firstVertical && secondDepth) || (secondVertical && firstDepth))) return null;

  const verticalProfile = firstVertical ? joint.first : joint.second;
  const verticalBox = firstVertical ? joint.firstBox : joint.secondBox;
  const depthProfile = firstDepth ? joint.first : joint.second;
  const depthBox = firstDepth ? joint.firstBox : joint.secondBox;
  const depthEnd = (firstDepth ? firstEnd : secondEnd)!;
  const moduleSize = Number(joint.series.slice(0, 2)) / SCENE_SCALE;
  const firstVerticalEndpoint = verticalBox.center.clone().addScaledVector(verticalBox.axes[0], verticalBox.halfSizes[0]);
  const secondVerticalEndpoint = verticalBox.center.clone().addScaledVector(verticalBox.axes[0], -verticalBox.halfSizes[0]);
  const baseY = Math.min(firstVerticalEndpoint.y, secondVerticalEndpoint.y);
  const topY = Math.max(firstVerticalEndpoint.y, secondVerticalEndpoint.y);
  const contactHeight = joint.contact.point.y - baseY;
  const frontTop = verticalProfile.remark?.includes('3.0展架前立柱')
    && depthProfile.remark?.includes('3.0展架下部')
    && Math.abs(topY - joint.contact.point.y) <= moduleSize * 0.75;
  if (!frontTop && (Math.abs(baseY) > moduleSize * 0.1 || contactHeight < -moduleSize * 0.1 || contactHeight > moduleSize * 0.75)) {
    return null;
  }
  return { verticalProfile, verticalBox, depthProfile, depthBox, depthEnd };
};


