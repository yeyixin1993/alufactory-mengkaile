type ParametricConnectionScope = string | ReadonlySet<string>;


const connectionScopeMatchesId = (scope: ParametricConnectionScope, id: string) => (
  typeof scope === 'string' ? id.startsWith(scope) : scope.has(id)
);


const connectionScopeMatchesProfile = (scope: ParametricConnectionScope, item: DIYSceneItem) => (
  item.kind === 'profile' && connectionScopeMatchesId(scope, item.id)
);


// Share the authoritative physical graph with No.5, machining and import.
// A profile end is attached once, to a carrier with a positive bearing area.
const parametricPhysicalConnections = (
  source: DIYSceneItem[],
  profileScope: ParametricConnectionScope,
): RackPhysicalConnection[] => {
  const ids = new Set(source.filter(item => connectionScopeMatchesProfile(profileScope, item)).map(item => item.id));
  const itemById = new Map(source.map(item => [item.id, item]));
  const jointByKey = new Map(autoConnectionJoints(source).map(joint => [joint.key, joint]));
  return scanPhysicalConnectionNodes(source, { profileIds: ids }).flatMap(node => {
    const joint = jointByKey.get(node.jointKey);
    const branchProfile = itemById.get(node.branchProfileId);
    const carrierProfile = itemById.get(node.carrierProfileId);
    if (!joint || !branchProfile || !carrierProfile) return [];
    return [{ joint, branchProfile, carrierProfile, branchEnd: node.branchEnd,
      carrierStationMm: node.carrierStationMm, carrierThrough: node.carrierThrough }];
  });
};


const itemOrientedBox = (
  item: DIYSceneItem,
  dimensions: [number, number, number],
  localOffset = new THREE.Vector3(),
): ProfileBox => {
  const quaternion = itemQuaternion(item);
  return {
    center: localOffset.applyQuaternion(quaternion).add(new THREE.Vector3(...item.position).multiplyScalar(1 / SCENE_SCALE)),
    axes: [
      new THREE.Vector3(1, 0, 0).applyQuaternion(quaternion).normalize(),
      new THREE.Vector3(0, 1, 0).applyQuaternion(quaternion).normalize(),
      new THREE.Vector3(0, 0, 1).applyQuaternion(quaternion).normalize(),
    ],
    halfSizes: dimensions.map((value) => Math.max(0.001, value / SCENE_SCALE / 2)) as [number, number, number],
  };
};


const displayRackConnectionObstacles = (source: DIYSceneItem[]) => source.flatMap((item): ProfileBox[] => {
  if (item.kind === 'marine_board' || item.kind === 'plate' || item.kind === 'pegboard') {
    const marker = readFittedPanelDraftMarker(item.fittedPanel, item.width || 1, item.height || 1);
    if (marker) {
      const solid = buildFittedPanelSolidCells(item.width || 1, item.height || 1, marker.cutouts);
      return solid.cells.map((cell) => itemOrientedBox(
        item,
        [cell.widthMm, cell.heightMm, item.thickness || 1],
        new THREE.Vector3(cell.centerXmm / SCENE_SCALE, cell.centerYmm / SCENE_SCALE, 0),
      ));
    }
    return [itemOrientedBox(item, [item.width || 1, item.height || 1, item.thickness || 1])];
  }
  if (item.kind === 'shelf_support' && item.shelfSupportType === 'drawer_slide_pair') {
    const spacing = Math.max(40, item.width || 727) / SCENE_SCALE;
    const railDimensions: [number, number, number] = [13, item.height || 45, item.length || item.thickness || 400];
    return [-1, 1].map((side) => itemOrientedBox(item, railDimensions, new THREE.Vector3(side * spacing / 2, 0, 0)));
  }
  return [];
});


const connectorSeatBoxes = (
  placement: AccessoryPlacement,
  series: '2020' | '3030' = '3030',
): ProfileBox[] => {
  const probe: DIYSceneItem = {
    ...createItem('connector', 0, series),
    position: placement.position.toArray().map((value) => value * SCENE_SCALE) as Vec3,
    rotation: placement.rotation,
  };
  const quaternion = itemQuaternion(probe);
  const firstArm = new THREE.Vector3(1, 0, 0).applyQuaternion(quaternion).normalize();
  const secondArm = new THREE.Vector3(0, 1, 0).applyQuaternion(quaternion).normalize();
  const localZ = new THREE.Vector3(0, 0, 1).applyQuaternion(quaternion).normalize();
  const origin = placement.position;
  const moduleSize = Number(series.slice(0, 2)) / SCENE_SCALE;
  const wallThickness = THREE.MathUtils.clamp(moduleSize * 0.18, 0.026, 0.06);
  const axes = [firstArm, secondArm, localZ] as [THREE.Vector3, THREE.Vector3, THREE.Vector3];
  return [{
    center: origin.clone().addScaledVector(firstArm, moduleSize / 2).addScaledVector(secondArm, wallThickness / 2),
    axes,
    halfSizes: [moduleSize / 2, wallThickness / 2, moduleSize / 2],
  }, {
    center: origin.clone().addScaledVector(firstArm, wallThickness / 2).addScaledVector(secondArm, moduleSize / 2),
    axes,
    halfSizes: [wallThickness / 2, moduleSize / 2, moduleSize / 2],
  }];
};


type DisplayRackConnectionCheck = { valid: boolean; issues: string[] };


const validateParametricConnectionSystem = (
  source: DIYSceneItem[],
  profileScope: ParametricConnectionScope,
  series: '2020' | '3030',
  modelLabel: string,
): DisplayRackConnectionCheck => {
  const issues: string[] = [];
  const required = parametricPhysicalConnections(source, profileScope);
  if (!required.length) issues.push(`${modelLabel}没有识别到可连接的型材节点`);
  const requiredByJoint = new Map(required.map((connection) => [connection.joint.key, connection]));
  const directHoles = source.flatMap((item) => connectionScopeMatchesProfile(profileScope, item)
    ? (item.holes || []).filter((hole) => hole.jointKey?.endsWith(':DRILL-TAP')).map((hole) => ({ item, hole }))
    : []);
  const connectors = source.filter((item) => (
    item.kind === 'connector'
    && Boolean(item.attachmentKey)
    && (item.attachedProfileIds || []).length === 2
    && item.accessoryProfileSize === series
    && (item.attachedProfileIds || []).every((id) => connectionScopeMatchesId(profileScope, id))
  ));
  const hiddenConnectors = source.filter((item) => (
    item.kind === 'hidden_connector'
    && Boolean(item.attachmentKey)
    && (item.attachedProfileIds || []).length === 2
    && item.accessoryProfileSize === series
    && (item.attachedProfileIds || []).every((id) => connectionScopeMatchesId(profileScope, id))
  ));
  const directByJoint = new Map<string, typeof directHoles>();
  directHoles.forEach((entry) => {
    const key = entry.hole.jointKey!.replace(/:DRILL-TAP$/, '');
    directByJoint.set(key, [...(directByJoint.get(key) || []), entry]);
  });
  const connectorByJoint = new Map<string, DIYSceneItem[]>();
  connectors.forEach((connector) => {
    const ids = [...(connector.attachedProfileIds || [])].sort();
    if (ids.length !== 2) issues.push(`角码${connector.id}没有绑定两根型材`);
    const key = ids.join(':JOINT:');
    connectorByJoint.set(key, [...(connectorByJoint.get(key) || []), connector]);
  });
  const hiddenByJoint = new Map<string, DIYSceneItem[]>();
  hiddenConnectors.forEach((connector) => {
    const key = no5JointKeyFor(connector);
    if (!key) issues.push(`5号隐藏连接${connector.id}没有绑定两根型材`);
    hiddenByJoint.set(key, [...(hiddenByJoint.get(key) || []), connector]);
  });
  const physicalNodes = no5NodeMap(source);

  required.forEach(({ joint }) => {
    const directCount = directByJoint.get(joint.key)?.length || 0;
    const connectorCount = connectorByJoint.get(joint.key)?.length || 0;
    const hiddenCount = hiddenByJoint.get(joint.key)?.length || 0;
    if (directCount + connectorCount + hiddenCount !== 1) {
      issues.push(`${joint.key}应且只能有一种连接，当前为${directCount}个直锁＋${connectorCount}个角码＋${hiddenCount}个5号隐藏连接`);
    }
  });
  directByJoint.forEach((rows, jointKey) => {
    if (!requiredByJoint.has(jointKey)) issues.push(`${jointKey}不是当前展架需要的有效直锁连接`);
    if (rows.length !== 1) issues.push(`${jointKey}存在${rows.length}个重复沉头孔`);
    if (connectorByJoint.has(jointKey) || hiddenByJoint.has(jointKey)) issues.push(`${jointKey}同时调用了直锁与连接配件`);
    const connection = requiredByJoint.get(jointKey);
    const plan = connection ? drillTapJointPlan(connection.joint) : null;
    if (!plan) {
      issues.push(`${jointKey}无法复核沉头孔与端面攻丝方向`);
    } else {
      const tapped = plan.tappedEnd < 0 ? plan.tappedProfile.tappingLeft : plan.tappedProfile.tappingRight;
      if (!tapped) issues.push(`${jointKey}缺少与沉头孔对应的端面攻丝`);
      rows.forEach(({ item, hole }) => {
        if (
          item.id !== plan.drilledProfile.id
          || hole.type !== plan.hole.type
          || hole.side !== plan.hole.side
          || Math.abs(hole.positionMm - plan.hole.positionMm) > 0.001
          || hole.physicalGrooveIndex !== plan.hole.physicalGrooveIndex
          || (plan.hole.fastenerSeat === 'internal_slot' && (
            hole.fastenerSeat !== 'internal_slot'
            || hole.fastenerHead !== 'button_socket'
            || hole.threadSize !== 'M8'
            || hole.fastenerLengthMm !== 20
            || (hole.fastenerDirection !== undefined && hole.fastenerDirection !== 'inward')
            || (hole.grooveIndex ?? 0) !== plan.hole.grooveIndex
          ))
        ) {
          issues.push(`${jointKey}的沉头孔位置、槽位或受力方向与连接规则不一致`);
        }
      });
    }
    rows.forEach(({ item, hole }) => {
      const screws = source.filter((candidate) => (
        candidate.kind === 'screw'
        && candidate.linkedProfileId === item.id
        && candidate.linkedHoleId === hole.id
      ));
      if (screws.length !== 1) issues.push(`${jointKey}的沉头孔没有唯一对应螺丝`);
    });
  });
  connectorByJoint.forEach((rows, jointKey) => {
    if (rows.length !== 1) issues.push(`${jointKey}存在${rows.length}个重复角码`);
    if (!requiredByJoint.has(jointKey)) issues.push(`${jointKey}不是当前展架需要的有效角码连接`);
    if (hiddenByJoint.has(jointKey)) issues.push(`${jointKey}同时调用了1号角码与5号隐藏连接`);
  });
  hiddenByJoint.forEach((rows, jointKey) => {
    if (rows.length !== 1) issues.push(`${jointKey}存在${rows.length}个重复5号隐藏连接`);
    if (!requiredByJoint.has(jointKey)) issues.push(`${jointKey}不是当前结构需要的有效5号隐藏连接`);
    const node = physicalNodes.get(jointKey);
    rows.forEach((connector) => {
      const report = node ? validateNo5SceneItem(connector, source, physicalNodes) : null;
      if (!report) {
        issues.push(`${jointKey}无法取得5号隐藏连接的权威物理节点`);
        return;
      }
      report.issues.forEach((entry) => issues.push(`${jointKey}：${entry.message}`));
      if (!no5ReportIsReady(report) && report.issues.length === 0) {
        issues.push(`${jointKey}的5号隐藏连接尚未通过槽位、工具净空与安装路径校验`);
      }
    });
  });
  const connectorKeys = connectors.map((item) => item.attachmentKey).filter(Boolean);
  if (new Set(connectorKeys).size !== connectorKeys.length) issues.push('存在重复的角码安装键');
  const hiddenConnectorKeys = hiddenConnectors.map((item) => item.attachmentKey).filter(Boolean);
  if (new Set(hiddenConnectorKeys).size !== hiddenConnectorKeys.length) issues.push('存在重复的5号隐藏连接安装键');

  const directCarrierStations = new Map<string, number>();
  directByJoint.forEach((rows, jointKey) => {
    if (!rows.length) return;
    const connection = requiredByJoint.get(jointKey);
    if (!connection) return;
    const stationKey = `${connection.carrierProfile.id}:${Math.round(connection.carrierStationMm * 10)}`;
    directCarrierStations.set(stationKey, (directCarrierStations.get(stationKey) || 0) + rows.length);
  });
  directCarrierStations.forEach((count, stationKey) => {
    if (count > 1) issues.push(`${stationKey}同一承载截面存在${count}条重复直锁路径`);
  });

  const probe = createItem('connector', source.length, series);
  const placementsByKey = new Map(accessoryPlacementCandidates(probe, source).map((placement) => [placement.key, placement]));
  const obstacleBoxes = displayRackConnectionObstacles(source);
  const checkedConnectorBoxes: { id: string; boxes: ProfileBox[] }[] = [];
  connectors.forEach((connector) => {
    const placement = connector.attachmentKey ? placementsByKey.get(connector.attachmentKey) : undefined;
    if (!placement) {
      issues.push(`角码${connector.id}没有可复核的双面贴合位置`);
      return;
    }
    const actualPosition = new THREE.Vector3(...connector.position).multiplyScalar(1 / SCENE_SCALE);
    if (actualPosition.distanceTo(placement.position) > 0.0001) {
      issues.push(`角码${connector.id}没有精确贴合到目标型材`);
    }
    const boxes = connectorSeatBoxes(placement, series);
    if (boxes.some((box) => obstacleBoxes.some((obstacle) => orientedBoxesOverlap(box, obstacle, 0.001)))) {
      issues.push(`角码${connector.id}与板件或抽屉滑轨发生物理冲突`);
    }
    if (boxes.some((box) => checkedConnectorBoxes.some((checked) => (
      checked.boxes.some((other) => orientedBoxesOverlap(box, other, 0.001))
    )))) {
      issues.push(`角码${connector.id}与其他连接配件发生物理冲突`);
    }
    checkedConnectorBoxes.push({ id: connector.id, boxes });
  });

  return { valid: issues.length === 0, issues };
};


type GuidedConnectionInspection = {
  valid: boolean;
  eligibleJointCount: number;
  connectedJointCount: number;
  missingJointCount: number;
  conflictJointCount: number;
  unsupportedJointCount: number;
  unconnectedProfileCount: number;
  interferingProfileCount: number;
  issues: string[];
};


const installedGuidedConnectionCounts = (source: DIYSceneItem[], joint: AutoConnectionJoint) => {
  const directKey = `${joint.key}:DRILL-TAP`;
  const directCount = source.reduce((count, item) => (
    item.kind === 'profile'
      ? count + (item.holes || []).filter((hole) => hole.jointKey === directKey).length
      : count
  ), 0);
  const targetIds = [joint.first.id, joint.second.id].sort().join('|');
  const bracketCount = source.filter((item) => (
    item.kind === 'connector'
    && (item.attachedProfileIds || []).length === 2
    && [...(item.attachedProfileIds || [])].sort().join('|') === targetIds
  )).length;
  const hiddenConnectors = source.filter((item) => (
    item.kind === 'hidden_connector'
    && (item.attachedProfileIds || []).length === 2
    && [...(item.attachedProfileIds || [])].sort().join('|') === targetIds
  ));
  const nodeByJoint = no5NodeMap(source);
  const validHiddenCount = hiddenConnectors.filter((connector) => (
    no5ReportIsReady(validateNo5SceneItem(connector, source, nodeByJoint))
  )).length;
  const unsupportedCount = source.filter((item) => (
    isConnectionAccessoryKind(item.kind)
    && item.kind !== 'connector'
    && item.kind !== 'hidden_connector'
    && (item.attachedProfileIds || []).length === 2
    && [...(item.attachedProfileIds || [])].sort().join('|') === targetIds
  )).length + hiddenConnectors.length - validHiddenCount;
  return {
    directCount,
    bracketCount,
    hiddenCount: hiddenConnectors.length,
    validHiddenCount,
    unsupportedCount,
  };
};


const guidedUnsupportedJointCount = (
  source: DIYSceneItem[],
  profileScope?: ReadonlySet<string>,
) => {
  const profiles = source.filter((item) => item.kind === 'profile');
  // A same-series perpendicular contact can be intentionally reduced out of
  // the final physical graph at a three-way corner. Keep every such candidate
  // approved here, while rejecting contacts that the verified 2020/3030
  // engine cannot reason about (mixed series, non-square or parallel ends,
  // and a guided member touching a member outside its persistent scope).
  const verifiedCandidateKeys = new Set(autoConnectionJoints(source)
    .filter((joint) => {
      const firstInScope = !profileScope || profileScope.has(joint.first.id);
      const secondInScope = !profileScope || profileScope.has(joint.second.id);
      return firstInScope && secondInScope;
    })
    .map((joint) => joint.key));
  let count = 0;
  profiles.forEach((first, firstIndex) => profiles.slice(firstIndex + 1).forEach((second) => {
    const firstInScope = !profileScope || profileScope.has(first.id);
    const secondInScope = !profileScope || profileScope.has(second.id);
    if (!firstInScope && !secondInScope) return;
    if (first.variantId === second.variantId && (first.variantId === '2020' || first.variantId === '3030')
      && Math.abs(profileBoxFromItem(first).axes[0].dot(profileBoxFromItem(second).axes[0])) <= 0.15
      && !scanPhysicalConnectionNodes([first, second]).length) return;
    const firstBox = profileBoxFromItem(first);
    const secondBox = profileBoxFromItem(second);
    const contact = profileContact(firstBox, secondBox);
    if (!contact) return;
    const [firstWidth, firstHeight] = profileSize(first.variantId);
    const [secondWidth, secondHeight] = profileSize(second.variantId);
    const moduleSize = Math.max(
      Math.min(firstWidth, firstHeight),
      Math.min(secondWidth, secondHeight),
    ) / SCENE_SCALE;
    if (
      profileEndpointSideAt(firstBox, contact.point, moduleSize) === null
      && profileEndpointSideAt(secondBox, contact.point, moduleSize) === null
    ) return;
    const jointKey = [first.id, second.id].sort().join(':JOINT:');
    if (verifiedCandidateKeys.has(jointKey)) return;
    count += 1;
  }));
  return count;
};


const inspectGuidedConnectionSystem = (
  source: DIYSceneItem[],
  profileScope?: ReadonlySet<string>,
): GuidedConnectionInspection => {
  const scopedProfiles = source.filter((item) => (
    item.kind === 'profile' && (!profileScope || profileScope.has(item.id))
  ));
  const supportedScopes = (['2020', '3030'] as const).map((series) => ({
    series,
    ids: new Set(scopedProfiles
      .filter((item) => item.variantId === series)
      .map((item) => item.id)),
  }));
  const required = supportedScopes.flatMap(({ ids }) => (
    ids.size ? parametricPhysicalConnections(source, ids) : []
  ));
  const connectedProfileIds = new Set(required.flatMap(({ joint }) => [joint.first.id, joint.second.id]));
  const unconnectedProfiles = scopedProfiles.filter((item) => !connectedProfileIds.has(item.id));
  const unconnectedProfileCount = unconnectedProfiles.length;
  let connectedJointCount = 0;
  let missingJointCount = 0;
  let conflictJointCount = 0;
  required.forEach(({ joint }) => {
    const counts = installedGuidedConnectionCounts(source, joint);
    const approvedCount = counts.directCount + counts.bracketCount + counts.validHiddenCount;
    if (approvedCount === 1 && counts.unsupportedCount === 0) connectedJointCount += 1;
    else if (approvedCount === 0 && counts.unsupportedCount === 0) missingJointCount += 1;
    else conflictJointCount += 1;
  });
  const unsupportedJointCount = guidedUnsupportedJointCount(source, profileScope);
  const interferingProfileCount = [...findCollidingProfileIds(source)]
    .filter((id) => !profileScope || profileScope.has(id)).length;
  const validationIssues = supportedScopes.flatMap(({ series, ids }) => {
    if (!ids.size || !parametricPhysicalConnections(source, ids).length) return [];
    return validateParametricConnectionSystem(source, ids, series, `引导搭建${series}`).issues;
  });
  const issues = [
    ...(!required.length ? ['没有识别到可自动连接的2020/3030型材节点'] : []),
    ...(missingJointCount ? [`还有${missingJointCount}处型材节点没有连接配件或直锁加工`] : []),
    ...(conflictJointCount ? [`有${conflictJointCount}处节点存在重复或非当前规则连接`] : []),
    ...(unsupportedJointCount ? [`有${unsupportedJointCount}处节点涉及尚未验证的混合规格或配件数据库`] : []),
    ...(unconnectedProfileCount ? [`有${unconnectedProfileCount}根型材没有参与任何已识别物理连接：${unconnectedProfiles.slice(0, 3).map((item) => item.name || item.id).join('、')}`] : []),
    ...(interferingProfileCount ? [`有${interferingProfileCount}根型材存在实体干涉`] : []),
    ...validationIssues,
  ].filter((issue, index, all) => all.indexOf(issue) === index);
  return {
    valid: required.length > 0
      && missingJointCount === 0
      && conflictJointCount === 0
      && unsupportedJointCount === 0
      && unconnectedProfileCount === 0
      && interferingProfileCount === 0
      && validationIssues.length === 0,
    eligibleJointCount: required.length,
    connectedJointCount,
    missingJointCount,
    conflictJointCount,
    unsupportedJointCount,
    unconnectedProfileCount,
    interferingProfileCount,
    issues,
  };
};


// The stool uses No.5 first, then true carrier-side drilling/branch tapping.
// All machining and linked screws share the existing validated adapters.
const completeStoolConnectionSystem = (source: DIYSceneItem[]) => {
  const scope = new Set(source.filter(item => item.kind === 'profile'
    && item.id.startsWith('parametric-stool-')).map(item => item.id));
  const nodes = scanPhysicalConnectionNodes(source, { profileIds: scope });
  const before = inspectGuidedConnectionSystem(source, scope);
  if (!nodes.length || before.interferingProfileCount || before.unsupportedJointCount) {
    return { items: source, check: { scope: 'native_frame_nodes' as const, valid: false, issues: before.issues }, inspection: before,
      assemblyReview: reviewStoolAssembly(source),
      partialApplied: false, no5RejectedJointKeys: [] as string[] };
  }
  let prepared = source;
  const no5RejectedJointKeys: string[] = [];
  for (const node of nodes) {
    const transaction = applyValidatedNo5ConnectionTransaction(prepared, new Set([node.jointKey]));
    if (transaction.failedJointKeys.length) no5RejectedJointKeys.push(node.jointKey);
    else prepared = transaction.items;
  }
  const rejected = new Set(no5RejectedJointKeys);
  const installedDrillKeys = new Set(scanPhysicalConnectionNodes(prepared, { profileIds: scope })
    .filter(node => node.installed.drill_tap.occurrenceCount === 1
      && node.installedMethods.length === 1).map(node => node.jointKey));
  const fallbackJoints = autoConnectionJoints(prepared)
    .filter(joint => rejected.has(joint.key) && !installedDrillKeys.has(joint.key));
  const plans = fallbackJoints.map(drillTapJointPlan)
    .filter((plan): plan is DrillTapJointPlan => Boolean(plan));
  const plannedKeys = new Set(plans.map(plan => plan.jointKey));
  for (const joint of fallbackJoints) {
    if (plannedKeys.has(`${joint.key}:DRILL-TAP`)) prepared = withoutConnectionArtifactsAtJoint(prepared, joint);
  }
  const machined = prepared.map(item => {
    if (item.kind !== 'profile') return item;
    const drilled = plans.filter(plan => plan.drilledProfile.id === item.id);
    const tapped = plans.filter(plan => plan.tappedProfile.id === item.id);
    if (!drilled.length && !tapped.length) return item;
    return { ...item, holes: [...(item.holes || []), ...drilled.map(plan => plan.hole)],
      tappingLeft: item.tappingLeft || tapped.some(plan => plan.tappedEnd < 0),
      tappingRight: item.tappingRight || tapped.some(plan => plan.tappedEnd > 0) };
  });
  prepared = synchronizeDesignerSceneItems(withAutoFilledScrews(machined, undefined,
    new Set(plans.map(plan => plan.hole.id))));
  // A neighboring direct screw can occupy a previously clear No.5 slot.
  // Select the existing internal-head kit only from explicit casting blockers,
  // then re-run the full scene including its real head/shaft and tool envelope.
  const blockedNo5ByScrew = new Map<string, Set<string>>();
  for (const connector of prepared.filter(item => item.kind === 'hidden_connector')) {
    const report = connector.no5Validation as No5ValidationReport | undefined;
    for (const check of report?.slotChecks || []) {
      if (check.code !== 'NO5_CASTING_OBSTRUCTION' || check.status !== 'block') continue;
      for (const blockerId of check.partIds) {
        const screw = prepared.find(item => item.id === blockerId && item.kind === 'screw');
        if (!screw?.linkedProfileId || !screw.linkedHoleId || !scope.has(screw.linkedProfileId)) continue;
        const profile = prepared.find(item => item.id === screw.linkedProfileId)!;
        const hole = profile.holes?.find(entry => entry.id === screw.linkedHoleId);
        if (!hole?.jointKey?.endsWith(':DRILL-TAP') || !rejected.has(hole.jointKey.slice(0, -10))) continue;
        const affected = blockedNo5ByScrew.get(screw.id) || new Set<string>();
        affected.add(connector.id);
        blockedNo5ByScrew.set(screw.id, affected);
      }
    }
  }
  if (blockedNo5ByScrew.size) {
    const internalHoleIds = new Set(prepared.filter(item => blockedNo5ByScrew.has(item.id)).map(item => item.linkedHoleId));
    const candidate = prepared.map(item => {
      if (item.kind !== 'profile') return item;
      return { ...item, holes: (item.holes || []).map(hole => internalHoleIds.has(hole.id) ? {
        ...hole, type: 'through' as const, fastenerSeat: 'internal_slot' as const,
        fastenerHead: 'button_socket' as const, threadSize: 'M8' as const, fastenerLengthMm: 20,
      } : hole) };
    });
    const allowedHoleIds = new Set(autoConnectionJoints(candidate).flatMap(joint => {
      const plan = drillTapJointPlan(joint);
      return plan?.hole.fastenerSeat === 'internal_slot'
        ? (plan.drilledProfile.holes || []).filter(hole => internalHoleIds.has(hole.id)
          && hole.jointKey === plan.jointKey && hole.side === plan.hole.side
          && Math.abs(hole.positionMm - plan.hole.positionMm) <= 0.001).map(hole => hole.id) : [];
    }));
    prepared = candidate.map(item => {
      if (item.kind === 'profile') {
        const previous = prepared.find(part => part.id === item.id)!;
        return { ...item, holes: (item.holes || []).map(hole => internalHoleIds.has(hole.id) && !allowedHoleIds.has(hole.id)
          ? previous.holes!.find(old => old.id === hole.id)! : hole) };
      }
      if (item.kind === 'screw' && allowedHoleIds.has(item.linkedHoleId || '')) {
        return { ...item, installBeforeIds: [...new Set([...(item.installBeforeIds || []), ...(blockedNo5ByScrew.get(item.id) || [])])],
          remark: `${item.remark || ''}｜M8×20内槽头座端攻丝连接，先紧固直锁、后装No.5；套装附带弹性扣件不参与本节点受力。` };
      }
      if (item.kind === 'hidden_connector') {
        const screwsBefore = [...blockedNo5ByScrew].filter(([id, ids]) => ids.has(item.id)
          && allowedHoleIds.has(prepared.find(part => part.id === id)?.linkedHoleId || '')).map(([id]) => id);
        if (screwsBefore.length) return { ...item, installAfterIds: [...new Set([...(item.installAfterIds || []), ...screwsBefore])] };
      }
      return item;
    });
    prepared = synchronizeDesignerSceneItems(prepared);
  }
  const inspection = inspectGuidedConnectionSystem(prepared, scope);
  return { items: prepared, check: { scope: 'native_frame_nodes' as const, valid: inspection.valid, issues: inspection.issues }, inspection,
    assemblyReview: reviewStoolAssembly(prepared),
    partialApplied: !inspection.valid && prepared !== source, no5RejectedJointKeys };
};


