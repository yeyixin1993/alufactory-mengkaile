const profileEndpointSideAt = (
  box: ProfileBox,
  point: THREE.Vector3,
  moduleSize: number,
): -1 | 1 | null => {
  const coordinate = point.clone().sub(box.center).dot(box.axes[0]);
  if (Math.abs(box.halfSizes[0] - Math.abs(coordinate)) > moduleSize * 0.7) return null;
  return coordinate >= 0 ? 1 : -1;
};


const autoConnectionJoints = (source: DIYSceneItem[]): AutoConnectionJoint[] => {
  const profiles = source.filter((item) => {
    if (item.kind !== 'profile') return false;
    const series = profileAccessorySeries(item);
    return series === '2020' || series === '3030';
  });
  const joints: AutoConnectionJoint[] = [];
  profiles.forEach((first, firstIndex) => profiles.slice(firstIndex + 1).forEach((second) => {
    const firstSeries = first.variantId;
    const secondSeries = second.variantId;
    if (firstSeries !== secondSeries || (firstSeries !== '2020' && firstSeries !== '3030')) return;
    const firstBox = profileBoxFromItem(first);
    const secondBox = profileBoxFromItem(second);
    if (Math.abs(firstBox.axes[0].dot(secondBox.axes[0])) > 0.15) return;
    // Use the same positive-area end/side contact as the decision engine.
    // A stacked frame's edge contact cannot become a second fastening node.
    const node = scanPhysicalConnectionNodes([first, second])[0];
    if (!node) return;
    const contact = { point: new THREE.Vector3(...node.contactPointMm).multiplyScalar(1 / SCENE_SCALE),
      size: profileContact(firstBox, secondBox)?.size || new THREE.Vector3() };
    joints.push({
      key: [first.id, second.id].sort().join(':JOINT:'),
      series: firstSeries,
      first,
      second,
      firstBox,
      secondBox,
      contact,
    });
  }));
  return joints;
};


const connectionAccessoryMatchesJoint = (
  item: DIYSceneItem,
  joint: AutoConnectionJoint,
) => {
  if (!isConnectionAccessoryKind(item.kind)) return false;
  if (item.attachmentKey === joint.key || item.attachmentKey?.startsWith(`${joint.key}:`)) return true;
  const targetIds = [joint.first.id, joint.second.id].sort();
  const attachedIds = [...(item.attachedProfileIds || [])].sort();
  return attachedIds.length === 2 && attachedIds.every((id, index) => id === targetIds[index]);
};


