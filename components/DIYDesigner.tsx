  const holeSummary = ([
    ['through', t.through],
    ['countersunk', t.countersunk],
    ['threaded', t.threaded],
  ] as Array<[HoleType, string]>)
    .filter(([type]) => holeCounts[type] > 0)
    .map(([type, label]) => `${label} ${holeCounts[type]}`);
